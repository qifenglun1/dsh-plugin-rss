    /** The active client transport; installed by apply() before any view renders. */
    let activeHostClient = null

    /**
     * Build the RSS client over the DSH Connection RPC channel. This uses the
     * page's installed transport (HTTP in a browser, the shell bridge in
     * Desktop) instead of calling window.fetch directly.
     * @param {object} connection - ctx.connection client service.
     */
    function createHostClient(connection) {
      const sleep = ms => new Promise(resolve => setTimeout(resolve, ms))
      const callOnce = async (endpoint, payload, signal) => {
        if (connection === undefined || connection === null) {
          const error = new Error('RSS host connection is unavailable.')
          error.code = 'connection_unavailable'
          throw error
        }
        const result = await connection.rpc.call('/api', 'rss.rpc', { endpoint, ...payload }, signal)
        if (result !== null && typeof result === 'object' && result.ok === true) return result.value
        const failure = result?.error ?? {}
        const error = new Error(failure.message ?? 'The RSS operation failed.')
        error.code = failure.code
        throw error
      }
      const wrapConnectionError = (error, endpoint) => {
        const message = error instanceof Error ? error.message : String(error)
        const wrapped = new Error(`Cannot reach the RSS service (${endpoint}). If DeepSeek Harness just restarted or the port changed, refresh the page and try again. ${message}`)
        wrapped.code = 'network_error'
        return wrapped
      }
      const call = async (endpoint, payload, signal) => {
        const method = payload?.method
        // Retry only read-only calls without a caller signal: a lost response must
        // never duplicate a refresh, AI request, or subscription change.
        const retryable = signal === undefined
          && (endpoint === 'state' || method === 'articles' || method === 'article' || method === 'aiModels')
        try {
          return await callOnce(endpoint, payload, signal)
        } catch (error) {
          if (error?.code !== undefined && error.code !== 'network_error') throw error
          if (!retryable) throw wrapConnectionError(error, endpoint)
          await sleep(350)
          try {
            return await callOnce(endpoint, payload, signal)
          } catch (second) {
            throw wrapConnectionError(second, endpoint)
          }
        }
      }
      return {
        state: signal => call('state', {}, signal),
        call: (method, params, signal) => call('call', { method, params: params ?? {} }, signal),
      }
    }

