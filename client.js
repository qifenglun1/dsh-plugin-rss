    function Modal({ t, title, onClose, children, footer, wide = false }) {
      const dialogRef = useRef(null)
      const restoreRef = useRef(null)
      const closeRef = useRef(onClose)
      closeRef.current = onClose
      const closeLabel = typeof t === 'function' ? t('dialog.close') : 'Close'
      useEffect(() => {
        restoreRef.current = document.activeElement
        const node = dialogRef.current
        if (node === null || node === undefined) return undefined
        const focusable = () => Array.from(node.querySelectorAll('button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])'))
          .filter(element => !element.disabled && element.getAttribute('aria-hidden') !== 'true')
        // Keep an autoFocus field inside the dialog; otherwise focus the first control.
        if (!node.contains(document.activeElement)) {
          const preferred = node.querySelector('input:not([type="hidden"]), textarea, select')
          const first = preferred ?? focusable()[0]
          if (first !== undefined && first !== null) first.focus()
          else node.focus()
        }
        const onKey = event => {
          if (event.key === 'Escape') {
            event.preventDefault()
            closeRef.current()
            return
          }
          if (event.key !== 'Tab') return
          const items = focusable()
          if (items.length === 0) {
            event.preventDefault()
            node.focus()
            return
          }
          const first = items[0]
          const last = items[items.length - 1]
          if (event.shiftKey && document.activeElement === first) {
            event.preventDefault()
            last.focus()
          } else if (!event.shiftKey && document.activeElement === last) {
            event.preventDefault()
            first.focus()
          }
        }
        node.addEventListener('keydown', onKey)
        return () => {
          node.removeEventListener('keydown', onKey)
          const previous = restoreRef.current
          if (previous !== null && previous !== undefined && previous.isConnected !== false && typeof previous.focus === 'function') previous.focus()
        }
      }, [])
      return h('div', { className: 'rss-overlay', role: 'presentation', onMouseDown: event => { if (event.target === event.currentTarget) onClose() } },
        h('div', {
          ref: dialogRef,
          tabIndex: -1,
          className: `rss-modal ${wide ? 'rss-modal-wide' : ''}`,
          role: 'dialog',
          'aria-modal': 'true',
          'aria-label': title,
        },
          h('div', { className: 'rss-modal-head' },
            h('h2', { className: 'rss-modal-title' }, title),
            h(IconButton, { icon: 'close', label: closeLabel, onClick: onClose })),
          h('div', { className: 'rss-modal-body' }, children),
          footer === undefined ? null : h('div', { className: 'rss-modal-foot' }, footer)))
    }

    function Banner({ t, message, kind = 'error', onRetry, onClose, action, role }) {
      if (message === null || message === undefined || message === '') return null
      // `role: null` opts out of the implicit live region when a persistent one announces the change.
      const liveRole = role === null ? undefined : (role ?? (kind === 'error' ? 'alert' : 'status'))
      return h('div', {
        className: `rss-banner rss-banner-row is-${kind}`,
        ...(liveRole === undefined ? {} : { role: liveRole }),
      },
        h('span', { className: 'rss-banner-text' }, message),
        action === undefined ? null : action,
        onRetry === undefined ? null : h('button', { type: 'button', className: 'rss-textbtn', onClick: onRetry }, t('error.retry')),
        onClose === undefined ? null : h(IconButton, { icon: 'close', size: 12, label: t('error.dismiss'), onClick: onClose, className: 'rss-banner-close' }))
    }

    function Toast({ toast, onDismiss }) {
      if (toast === null || toast === undefined) return null
      const kind = toast.kind ?? 'ok'
      const action = toast.action
      return h('div', {
        className: `rss-toast is-${kind}`,
        role: kind === 'error' ? 'alert' : 'status',
        'aria-live': kind === 'error' ? 'assertive' : 'polite',
      },
        h('span', { className: 'rss-toast-text' }, toast.text),
        action === null || action === undefined
          ? null
          : h('button', {
            type: 'button',
            className: 'rss-toast-action',
            onClick: () => {
              onDismiss()
              void Promise.resolve()
                .then(action.onClick)
                .catch(() => {})
            },
          }, action.label))
    }

