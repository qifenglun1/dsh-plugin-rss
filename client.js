    /** Read a file as text, honoring UTF-16 BOMs that some OPML exporters emit. */
    async function readFileText(file) {
      const bytes = new Uint8Array(await file.arrayBuffer())
      if (bytes.length > 2 && bytes[0] === 0xff && bytes[1] === 0xfe) return new TextDecoder('utf-16le').decode(bytes)
      if (bytes.length > 2 && bytes[0] === 0xfe && bytes[1] === 0xff) return new TextDecoder('utf-16be').decode(bytes)
      return new TextDecoder('utf-8').decode(bytes)
    }

    /** Render the small Markdown subset the AI replies use. */
    function renderRich(text, keyPrefix = 'md') {
      const lines = String(text ?? '').split('\n')
      const nodes = []
      let list = []
      const flushList = () => {
        if (list.length === 0) return
        nodes.push(h('ul', { key: `${keyPrefix}-ul-${nodes.length}` }, ...list))
        list = []
      }
      lines.forEach((line, index) => {
        const bullet = /^\s*[-*]\s+(.*)$/.exec(line)
        const heading = /^\s*(#{1,4})\s+(.*)$/.exec(line)
        if (bullet !== null) {
          list.push(h('li', { key: `${keyPrefix}-li-${index}` }, inline(bullet[1], `${keyPrefix}-i-${index}`)))
          return
        }
        flushList()
        if (heading !== null) {
          nodes.push(h('div', { key: `${keyPrefix}-h-${index}`, className: 'rss-rich-h' }, inline(heading[2], `${keyPrefix}-hi-${index}`)))
        } else if (line.trim() === '') {
          nodes.push(h('div', { key: `${keyPrefix}-sp-${index}`, className: 'rss-rich-sp' }))
        } else {
          nodes.push(h('p', { key: `${keyPrefix}-p-${index}` }, inline(line, `${keyPrefix}-ii-${index}`)))
        }
      })
      flushList()
      return nodes
    }

    function safeLink(url) {
      return /^https?:\/\//i.test(String(url ?? '')) ? String(url) : undefined
    }

    /** Inline formatting: bold, code, and safe links. */
    function inline(text, keyPrefix) {
      const parts = []
      const pattern = /(\*\*([^*]+)\*\*|`([^`]+)`|\[([^\]]+)\]\(([^)\s]+)\))/g
      let cursor = 0
      let match
      let index = 0
      while ((match = pattern.exec(text)) !== null) {
        if (match.index > cursor) parts.push(text.slice(cursor, match.index))
        if (match[2] !== undefined) parts.push(h('strong', { key: `${keyPrefix}-b-${index}` }, match[2]))
        else if (match[3] !== undefined) parts.push(h('code', { key: `${keyPrefix}-c-${index}`, className: 'rss-code' }, match[3]))
        else {
          const href = safeLink(match[5])
          parts.push(href === undefined
            ? match[4]
            : h('a', { key: `${keyPrefix}-a-${index}`, href, target: '_blank', rel: 'noopener noreferrer' }, match[4]))
        }
        cursor = match.index + match[0].length
        index += 1
      }
      if (cursor < text.length) parts.push(text.slice(cursor))
      return parts
    }

