    /* ------------------------------------------------------------------ *
     * Client plugin
     * ------------------------------------------------------------------ */

    return {
      inject: ['slots', 'locale', 'connection', 'remote', 'remote.pluginManager'],
      apply(ctx) {
        activeHostClient = createHostClient(ctx.connection)
        ctx.effect(() => ctx.locale.register('rss', { en: dictEn, zh: dictZh }), 'rss: dictionaries')
        const t = ctx.locale.bind('rss')
        const updateStore = createUpdateStore()

        let updateRequest = null
        let updateCheckedAt = 0
        let updateRetry = null
        let updateRetries = 0

        /** The Remote namespace can mount just after the first sidebar render. */
        function retryUpdateCheck() {
          if (updateRetry !== null || updateRetries >= 5) return
          updateRetries += 1
          updateRetry = setTimeout(() => {
            updateRetry = null
            updateRequest = null
            void checkForUpdate()
          }, 1500)
        }

        ctx.effect(() => () => {
          if (updateRetry !== null) clearTimeout(updateRetry)
        }, 'rss: update-check retry')

        /** Ask the Host for newer registry versions; a panel remount rechecks at most every 10 minutes. */
        function checkForUpdate() {
          if (updateRequest !== null && Date.now() - updateCheckedAt < UPDATE_RECHECK_MS) return updateRequest
          let manager
          try {
            manager = ctx.remote?.pluginManager
          } catch {
            // The reader can mount while the optional update check is unavailable.
            return Promise.resolve()
          }
          if (manager === undefined || typeof manager.listVersions !== 'function') {
            retryUpdateCheck()
            return Promise.resolve()
          }
          if (updateRetry !== null) {
            clearTimeout(updateRetry)
            updateRetry = null
          }
          updateCheckedAt = Date.now()
          updateStore.set({ status: 'checking', version: null, registry: null })
          updateRequest = (async () => {
            try {
              const answer = await manager.listVersions(UPDATE_PACKAGE, {})
              const update = answer?.ok ? selectUpdate(answer.value) : null
              updateRetries = 0
              updateStore.set({ status: 'done', version: update?.version ?? null, registry: update?.registry ?? null })
            } catch {
              // Unsupported Host, denied access or a failed registry read: stay
              // quiet, and let the next panel mount try again.
              updateRequest = null
              updateCheckedAt = 0
              updateStore.set(IDLE_UPDATE)
            }
          })()
          return updateRequest
        }

        /** Open this bundle's page in Plugins, where DSH runs the confirmed update. */
        function openUpdatePage() {
          const navigation = ctx.reflect.get('pluginNavigation')
          if (navigation !== null && navigation !== undefined && typeof navigation.openBundle === 'function') {
            // The return from Plugins rechecks, so an installed update clears the notice.
            updateRequest = null
            updateCheckedAt = 0
            navigation.openBundle(UPDATE_PACKAGE)
          }
        }

        ctx.slots.inject('main', () => ctx.slots.register({
          name: 'main',
          key: 'rss',
          locale: 'rss',
          inject: () => ({ t, updateStore, checkForUpdate, openUpdatePage }),
        }, RssPage))

        ctx.slots.inject('sidebar.panellist', () => ctx.slots.register({
          name: 'sidebar.panellist',
          id: 'rss',
          order: 25,
          locale: 'rss',
          label: () => t('panel'),
        }, RssIcon))
      },
    }
